"""Build a VPM ZIP and, when --repository is supplied, a GitHub Pages listing."""
import argparse
import hashlib
import html
import json
from pathlib import Path
import re
import shutil
import urllib.parse
import urllib.request
import urllib.error
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "Packages/net.l1zerox.radialinventory"


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def collect_files():
    allowed = {".cs", ".meta", ".asmdef", ".json", ".png", ".ps1", ".md", ".bat", ".uxml", ".uss"}
    files = sorted(p for p in PACKAGE.rglob("*") if p.is_file())
    for p in files:
        rel = p.relative_to(PACKAGE).as_posix()
        if p.is_symlink() or (p.suffix not in allowed and rel != "LICENSE"):
            raise ValueError(f"Unexpected distribution file: {rel}")
        if re.search(r"(^|/)(Assets|Library|Temp|Logs|AutoGenerated|KaiIcons|\.git)/|Verification|settings\.json|\.bak$", rel):
            raise ValueError(f"Private/generated/test file: {rel}")
        if p.suffix != ".png":
            content = p.read_text(encoding="utf-8-sig")
            if re.search(r"[A-Za-z]:[\\/](?:Users|Documents|Pictures)[\\/]|萌_2024|愛莉real影|lilToon_Airi|bc1f063c-b747", content):
                raise ValueError(f"Personal development data: {rel}")
        if p.suffix == ".meta" and not Path(str(p)[:-5]).exists():
            raise ValueError(f"Orphan meta: {rel}")
    return files


def build(output, repository=None, previous=None, fetch_previous=False):
    manifest = read_json(PACKAGE / "package.json")
    version = manifest["version"]
    package_id = manifest["name"]
    if package_id != "net.l1zerox.radialinventory" or not re.fullmatch(r"\d+\.\d+\.\d+(?:-beta\.[1-9]\d*)?", version):
        raise ValueError("Unexpected package ID or non-release version")
    if manifest.get("legacyPackages") != ["yagihata.radialinventorysystem.v4"]:
        raise ValueError("Original package replacement declaration missing")
    if "Copyright 2020 Yagihata" not in (PACKAGE / "LICENSE").read_text():
        raise ValueError("Original copyright missing")
    files = collect_files()
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    archive = output / f"{package_id}-{version}.zip"
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in files:
            entry = zipfile.ZipInfo(p.relative_to(PACKAGE).as_posix(), (2020, 1, 1, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            entry.create_system = 3
            entry.external_attr = 0o100644 << 16
            z.writestr(entry, p.read_bytes())
    with zipfile.ZipFile(archive) as z:
        assert z.testzip() is None
        assert json.loads(z.read("package.json")) == manifest
        assert "LICENSE" in z.namelist() and "Editor/MainWindow.cs" in z.namelist()
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    (output / "SHA256SUMS.txt").write_text(f"{digest}  {archive.name}\n", encoding="utf-8")
    report = {"version": version, "archive": archive.name, "sha256": digest,
              "files": len(files), "checks": ["VPM ZIP root", "ZIP CRC", "manifest", "MIT copyright", "original package replacement", "distribution file scan"],
              "listingGenerated": False, "published": False, "prerelease": "-" in version}
    if repository:
        if not re.fullmatch(r"[A-Za-z0-9-]+/[A-Za-z0-9_.-]+", repository):
            raise ValueError("repository must be owner/repository")
        owner, repo = repository.split("/")
        base = f"https://{owner.lower()}.github.io/"
        if repo.lower() != owner.lower() + ".github.io":
            base += urllib.parse.quote(repo, safe="") + "/"
        listing_url = base + "index.json"
        listing = {"name": "衣装簡単切替ツール", "id": "net.l1zerox.radialinventory.listing",
                   "url": listing_url, "author": "L1ZeroX", "packages": {}}
        old = None
        if previous:
            old = read_json(previous)
        elif fetch_previous:
            try:
                with urllib.request.urlopen(listing_url, timeout=30) as response:
                    old = json.load(response)
            except urllib.error.HTTPError as error:
                if error.code != 404:
                    raise
        if old:
            if old.get("id") != listing["id"] or old.get("url") != listing_url:
                raise ValueError("Existing listing belongs to another repository")
            listing["packages"] = old["packages"]
        published_manifest = dict(manifest)
        published_manifest["url"] = f"https://github.com/{repository}/releases/download/v{version}/{archive.name}"
        published_manifest["zipSHA256"] = digest
        versions = listing["packages"].setdefault(package_id, {"versions": {}})["versions"]
        if version in versions and versions[version] != published_manifest:
            raise ValueError("This version is already published with different contents; increment the version")
        versions[version] = published_manifest
        site = output / "site"
        site.mkdir(exist_ok=True)
        write_json(site / "index.json", listing)
        write_json(output / f"{package_id}-{version}.json", published_manifest)
        add_url = "vcc://vpm/addRepo?url=" + urllib.parse.quote(listing_url, safe="")
        page = (ROOT / "site/index.template.html").read_text(encoding="utf-8")
        asset_version = hashlib.sha256(b"".join(p.read_bytes() for p in sorted((ROOT / "site/assets").iterdir()) if p.is_file())).hexdigest()[:12]
        stable = [v for v in versions if re.fullmatch(r"\d+\.\d+\.\d+", v)]
        stable_version = max(stable, key=lambda v: tuple(map(int, v.split('.')))) if stable else version
        shown = versions[stable_version] if report["prerelease"] and stable else published_manifest
        notice = (f"UI Toolkit ベータ版 v{version} を公開中。VCCの Settings → Packages → Show Pre-Release Packages をONにして選択できます。専用編集の一部は互換UIです。" if report["prerelease"] else "")
        for key, value in {"VERSION": shown["version"], "CHANNEL_NOTICE": notice, "LISTING_URL": listing_url, "ADD_URL": add_url,
                           "ASSET_VERSION": asset_version,
                           "REPOSITORY_URL": f"https://github.com/{repository}", "ZIP_URL": shown["url"]}.items():
            page = page.replace("{{" + key + "}}", html.escape(value, quote=True))
        (site / "index.html").write_text(page, encoding="utf-8")
        shutil.copytree(ROOT / "site/assets", site / "assets", dirs_exist_ok=True)
        (site / ".nojekyll").write_text("", encoding="utf-8")
        report.update(listingGenerated=True, listingUrl=listing_url)
    write_json(output / "verification.json", report)
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default=str(ROOT / "dist"))
    parser.add_argument("--repository", help="Actual GitHub owner/repository, never a placeholder")
    parser.add_argument("--previous", help="Existing index.json, retaining earlier versions")
    parser.add_argument("--fetch-previous", action="store_true")
    args = parser.parse_args()
    build(args.output, args.repository, args.previous, args.fetch_previous)

import contextlib
import io
import json
from pathlib import Path
import tempfile
import unittest
import zipfile

from build_release import build, PACKAGE, read_json


class DistributionTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.output = Path(self.temp.name)

    def build(self, folder, **kwargs):
        with contextlib.redirect_stdout(io.StringIO()):
            return build(self.output / folder, **kwargs)

    def test_package_root_integrity_and_no_listing_without_host(self):
        report = self.build("local")
        with zipfile.ZipFile(self.output / "local" / report["archive"]) as archive:
            self.assertIsNone(archive.testzip())
            self.assertEqual(json.loads(archive.read("package.json")), read_json(PACKAGE / "package.json"))
            self.assertIn("LICENSE", archive.namelist())
            self.assertIn("install.bat", archive.namelist())
            self.assertTrue(all(not n.startswith("net.l1zerox.radialinventory/") for n in archive.namelist()))
            self.assertTrue(all("Verification" not in n and "AutoGenerated" not in n for n in archive.namelist()))
        self.assertFalse((self.output / "local/site").exists())

    def test_reproducible_zip(self):
        self.assertEqual(self.build("first")["sha256"], self.build("second")["sha256"])

    def test_standalone_dependency_activation(self):
        manifest = read_json(PACKAGE / "package.json")
        self.assertNotIn("yagihata.radialinventorysystem.v4", manifest.get("vpmDependencies", {}))
        for folder, name in [("Editor", "yagihata.radialinventorysystem.v4.Editor"), ("Runtime", "yagihata.radialinventorysystem.v4")]:
            definition = read_json(PACKAGE / folder / (name + ".asmdef"))
            activation = [v for v in definition["versionDefines"] if v["define"] == "RISV4_JSON"]
            self.assertEqual(len(activation), 1)
            self.assertEqual(activation[0]["name"], "com.unity.nuget.newtonsoft-json")
            self.assertIn(activation[0]["name"], manifest["dependencies"])

    def test_listing_hash_urls_and_previous_versions(self):
        self.build("first", repository="example-tests/wardrobe-switch-tool")
        old_path = self.output / "first/site/index.json"
        old = read_json(old_path)
        versions = old["packages"]["net.l1zerox.radialinventory"]["versions"]
        versions["1.0.0"] = {"name": "net.l1zerox.radialinventory", "version": "1.0.0", "url": "https://example.invalid/old.zip"}
        old_path.write_text(json.dumps(old), encoding="utf-8")
        report = self.build("second", repository="example-tests/wardrobe-switch-tool", previous=old_path)
        result = read_json(self.output / "second/site/index.json")
        versions = result["packages"]["net.l1zerox.radialinventory"]["versions"]
        self.assertIn("1.0.0", versions)
        self.assertEqual(versions[report["version"]]["zipSHA256"], report["sha256"])
        self.assertEqual(result["url"], "https://example-tests.github.io/wardrobe-switch-tool/index.json")
        self.assertIn("/releases/download/v" + report["version"] + "/", versions[report["version"]]["url"])
        page = (self.output / "second/site/index.html").read_text(encoding="utf-8")
        self.assertNotIn("{{", page)
        self.assertIn("vcc://vpm/addRepo?url=https%3A%2F%2F", page)

    def test_reject_overwriting_version(self):
        report = self.build("first", repository="example-tests/wardrobe-switch-tool")
        old_path = self.output / "first/site/index.json"
        old = read_json(old_path)
        old["packages"]["net.l1zerox.radialinventory"]["versions"][report["version"]]["zipSHA256"] = "0" * 64
        old_path.write_text(json.dumps(old), encoding="utf-8")
        with self.assertRaisesRegex(ValueError, "already published"):
            self.build("second", repository="example-tests/wardrobe-switch-tool", previous=old_path)

    def test_reject_wrong_repository(self):
        with self.assertRaisesRegex(ValueError, "owner/repository"):
            self.build("bad", repository="https://github.com/owner/repo")


if __name__ == "__main__":
    unittest.main()

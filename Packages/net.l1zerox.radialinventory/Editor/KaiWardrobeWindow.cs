using System;
using System.IO;
using System.Linq;
using System.Diagnostics;
using UnityEditor;
using UnityEngine;
using VRC.SDK3.Avatars.Components;
using VRC.SDK3.Avatars.ScriptableObjects;

namespace YagihataItems.RadialInventorySystemV4
{
    public sealed class KaiWardrobeWindow : EditorWindow
    {
        Avatar data;
        string[] files = new string[0];
        string query = "", status = "";
        int fileIndex, groupIndex;
        float yaw, zoom = 1;
        bool diagnostics;
        bool focusClothing = true;
        Vector2 scroll;
        void OnEnable() { titleContent = new GUIContent("衣装簡単切替ツール"); }
        [MenuItem("衣装簡単切替ツール/補助ツール（検索・一括登録・移行）", priority = 10)]
        static void ShowWindow() { Open(null); }
        public static void Open(Avatar avatar)
        {
            var window = GetWindow<KaiWardrobeWindow>("衣装簡単切替ツール");
            window.titleContent = new GUIContent("衣装簡単切替ツール");
            window.data = avatar;
            window.ReloadFiles();
            window.minSize = new Vector2(560, 440);
        }
        void ReloadFiles()
        {
            files = Directory.Exists(RIS.AutoGeneratedFolderPath) ? Directory.GetFiles(RIS.AutoGeneratedFolderPath, RIS.SettingsFileName, SearchOption.AllDirectories) : new string[0];
        }
        void Run(Action action)
        {
            try { action(); }
            catch (Exception ex) { status = ex.Message; UnityEngine.Debug.LogException(ex); }
        }
        void Launcher(string action, string backup = null)
        {
            // Scripts without an asmdef are compiled into Assembly-CSharp-Editor.
            var script = AssetDatabase.FindAssets("KaiWardrobeWindow t:MonoScript").Select(AssetDatabase.GUIDToAssetPath).FirstOrDefault(p => p.EndsWith("/KaiWardrobeWindow.cs"));
            string root = script == null ? "Packages/net.l1zerox.radialinventory" : Path.GetDirectoryName(Path.GetDirectoryName(script));
            string ps = Path.GetFullPath(Path.Combine(root, "Tools", "Migrate.ps1"));
            string project = Path.GetFullPath(".");
            string args = "-NoProfile -ExecutionPolicy Bypass -File \"" + ps + "\" -Action " + action + " -ProjectPath \"" + project + "\"";
            if (backup != null) args += " -BackupPath \"" + backup + "\" -WaitForEditor";
            Process.Start(new ProcessStartInfo("powershell.exe", args) { UseShellExecute = true, WindowStyle = ProcessWindowStyle.Hidden });
            status = action == "Restore" ? "Unityを閉じると復元します。結果はプロジェクト外の移行ログで確認できます。" : "バックアップを開始しました。完了結果は移行ログで確認できます。";
        }
        void OnGUI()
        {
            EditorGUILayout.LabelField("衣装画像・一括登録・移行", EditorStyles.boldLabel);
            if (GUILayout.Button("既存V4設定を再検索")) ReloadFiles();
            if (files.Length > 0)
            {
                fileIndex = Mathf.Clamp(fileIndex, 0, files.Length - 1);
                fileIndex = EditorGUILayout.Popup("既存設定", fileIndex, files.Select(f => Path.GetFileName(Path.GetDirectoryName(f))).ToArray());
                if (GUILayout.Button("選択した設定を読み込む")) Run(() => { data = Avatar.LoadFromJson(files[fileIndex]); status = "読み込みました。アバターと参照を確認してください。"; });
            }
            if (data == null) { EditorGUILayout.HelpBox("元のRISV4 Editorで設定を作成するか、既存設定を読み込んでください。", MessageType.Info); return; }
            KaiAutoThumbnail.DrawSettings(data);
            var avatar = data.GetAvatarRoot();
            var next = (VRCAvatarDescriptor)EditorGUILayout.ObjectField("対象アバター", avatar, typeof(VRCAvatarDescriptor), true);
            if (next != avatar) { data.AvatarRoot = new GUIDPathPair<VRCAvatarDescriptor>(ObjectPathStateType.Scene, next); data.ForceReload(); }
            EditorGUILayout.BeginHorizontal();
            if (GUILayout.Button("設定を保存")) Run(() => { data.SaveToJson(); status = "保存しました。"; });
            if (GUILayout.Button("メニュー・画像を反映")) Run(() => { KaiPreflight.Require(data); data.SaveToJson(); data.ReCreateExpressionMenu(); status = "メニューを更新しました。新規衣装の切替生成は元のEditorの適用を使用してください。"; });
            if (GUILayout.Button("バックアップ")) Run(() => { data.SaveToJson(); UnityEditor.SceneManagement.EditorSceneManager.SaveOpenScenes(); Launcher("Backup"); });
            if (GUILayout.Button("復元")) Run(() => {
                string selected = EditorUtility.OpenFolderPanel("復元するバックアップ（backup.jsonのあるフォルダー）", Path.Combine(Path.GetFullPath(".."), "RI-Kai-Backups"), "");
                if (!string.IsNullOrEmpty(selected)) Launcher("Restore", selected);
            });
            EditorGUILayout.EndHorizontal();
            if (GUILayout.Button("衣装の切替も生成（FX・パラメーター・メニューを適用）")) Run(() =>
            {
                EditorTab builder = data.MenuMode == RIS.MenuModeType.Simple ? (EditorTab)new TabSimple() : data.MenuMode == RIS.MenuModeType.Basic ? (EditorTab)new TabBasic() : new TabAdvanced();
                var errors = builder.CheckErrors(ref data);
                if (errors.Length > 0) throw new InvalidOperationException(string.Join("\n", errors));
                KaiPreflight.Require(data);
                data.SaveToJson();
                builder.ApplyToAvatar(ref data);
                status = "衣装の切替とメニューを生成しました。シーンを保存してください。";
            });
            int cost = KaiPreflight.Cost(data);
            EditorGUILayout.HelpBox("同期容量 " + cost + " / " + VRCExpressionParameters.MAX_PARAMETER_COST + " bits ・ グループ " + data.Groups.Count + "個 / " + KaiMenuBuilder.PageCount(data.Groups.Count) + "ページ", cost > VRCExpressionParameters.MAX_PARAMETER_COST ? MessageType.Error : MessageType.Info);
            if (data.Groups.Count == 0) return;
            groupIndex = Mathf.Clamp(groupIndex, 0, data.Groups.Count - 1);
            groupIndex = EditorGUILayout.Popup("グループ", groupIndex, data.Groups.Select((g, i) => i + ": " + g.Name).ToArray());
            var group = data.Groups[groupIndex];
            diagnostics = EditorGUILayout.Foldout(diagnostics, "移行診断・参照の修正");
            if (diagnostics)
            {
                var issues = KaiDiagnostics.Inspect(data);
                EditorGUILayout.HelpBox(issues.Count == 0 ? "設定を読み込みました。未解決の参照はありません。" : string.Join("\n", issues), issues.Count == 0 ? MessageType.Info : MessageType.Warning);
                group.Icon = AssetField("グループ画像", group.Icon);
                group.BaseMenu = AssetField("既存メニュー", group.BaseMenu);
            }
            EditorGUILayout.LabelField("衣装 " + group.Props.Count + "個 / " + KaiMenuBuilder.PageCount(group.Props.Count + (group.UseResetButton ? 1 : 0) + (group.BaseMenu?.GetObject()?.controls.Count ?? 0)) + "ページ");
            query = EditorGUILayout.TextField("検索", query);
            yaw = EditorGUILayout.Slider("撮影の向き", yaw, -180, 180);
            focusClothing = EditorGUILayout.Toggle("衣装の範囲に合わせる", focusClothing);
            zoom = EditorGUILayout.Slider("撮影ズーム", zoom, 0.5f, 3);
            Rect drop = GUILayoutUtility.GetRect(0, 44, GUILayout.ExpandWidth(true));
            GUI.Box(drop, "ここへアバター内の衣装オブジェクトをまとめてドラッグ");
            if (drop.Contains(Event.current.mousePosition) && (Event.current.type == EventType.DragUpdated || Event.current.type == EventType.DragPerform))
            {
                DragAndDrop.visualMode = DragAndDropVisualMode.Copy;
                if (Event.current.type == EventType.DragPerform) { DragAndDrop.AcceptDrag(); Run(() => AddObjects(group)); }
                Event.current.Use();
            }
            scroll = EditorGUILayout.BeginScrollView(scroll);
            for (int i = 0; i < group.Props.Count; i++)
            {
                var prop = group.Props[i];
                string name = prop.GetPropName(data);
                if (!string.IsNullOrEmpty(query) && (name ?? "").IndexOf(query, StringComparison.OrdinalIgnoreCase) < 0) continue;
                EditorGUILayout.BeginVertical(EditorStyles.helpBox);
                EditorGUILayout.BeginHorizontal();
                var icon = prop.Icon?.GetObject();
                GUILayout.Label(icon, GUILayout.Width(64), GUILayout.Height(64));
                EditorGUILayout.BeginVertical();
                prop.Name = EditorGUILayout.TextField("衣装名", name);
                var newIcon = (Texture2D)EditorGUILayout.ObjectField("画像を指定", icon, typeof(Texture2D), false);
                if (newIcon != icon) prop.Icon = new GUIDPathPair<Texture2D>(ObjectPathStateType.Asset, newIcon);
                if (GUILayout.Button(icon == null ? "自動撮影" : "撮り直し")) Run(() => { KaiThumbnail.Capture(data, prop, yaw, zoom, focusClothing); data.SaveToJson(); status = "撮影しました。「メニュー・画像を反映」で反映できます。"; });
                EditorGUILayout.EndVertical();
                if (GUILayout.Button("↑", GUILayout.Width(28)) && i > 0) { group.Props.RemoveAt(i); group.Props.Insert(i - 1, prop); KaiReferences.PropMoved(data, group, i, i - 1); GUIUtility.ExitGUI(); }
                if (GUILayout.Button("↓", GUILayout.Width(28)) && i + 1 < group.Props.Count) { group.Props.RemoveAt(i); group.Props.Insert(i + 1, prop); KaiReferences.PropMoved(data, group, i, i + 1); GUIUtility.ExitGUI(); }
                EditorGUILayout.EndHorizontal();
                if (avatar != null)
                {
                    for (int t = 0; t < prop.TargetObjects.Count; t++)
                    {
                        var reference = prop.TargetObjects[t];
                        var old = reference?.GetObject(avatar.gameObject);
                        var replacement = (GameObject)EditorGUILayout.ObjectField(old == null ? "参照不明: " + reference?.GetFormattedPath() : "対象", old, typeof(GameObject), true);
                        if (replacement != old && (replacement == null || replacement.transform.IsChildOf(avatar.transform)))
                            prop.TargetObjects[t] = new GUIDPathPair<GameObject>(ObjectPathStateType.RelativeFromObject, replacement, avatar.gameObject);
                    }
                }
                if (diagnostics)
                {
                    prop.EnableAnimation = AssetField("ONアニメーション", prop.EnableAnimation);
                    prop.DisableAnimation = AssetField("OFFアニメーション", prop.DisableAnimation);
                    for (int m = 0; m < prop.MaterialOverrides.Count; m++)
                        prop.MaterialOverrides[m] = AssetField("マテリアル " + m, prop.MaterialOverrides[m]);
                }
                EditorGUILayout.EndVertical();
            }
            EditorGUILayout.EndScrollView();
            KaiAutoThumbnail.Observe(data);
            if (!string.IsNullOrEmpty(status)) EditorGUILayout.HelpBox(status, MessageType.Info);
        }
        static GUIDPathPair<T> AssetField<T>(string label, GUIDPathPair<T> reference) where T : UnityEngine.Object
        {
            var current = reference?.GetObject();
            var selected = (T)EditorGUILayout.ObjectField(label, current, typeof(T), false);
            return selected == current ? reference : new GUIDPathPair<T>(ObjectPathStateType.Asset, selected);
        }
        void AddObjects(Group group)
        {
            KaiAutoThumbnail.Observe(data);
            var root = data.GetAvatarRoot();
            if (root == null) throw new InvalidOperationException("対象アバターを指定してください。");
            if (data.MenuMode == RIS.MenuModeType.Simple && groupIndex == 7) throw new InvalidOperationException("このグループは衣装セット専用です。元のEditorでセットを登録してください。");
            var objects = DragAndDrop.objectReferences.OfType<GameObject>().ToArray();
            if (objects.Any(o => o == root.gameObject || !o.transform.IsChildOf(root.transform))) throw new InvalidOperationException("対象アバター配下の衣装だけを登録できます。");
            foreach (var obj in objects)
            {
                if (group.Props.Any(p => p.TargetObjects.Any(r => r?.GetObject(root.gameObject) == obj))) continue;
                var prop = new Prop { Name = obj.name, IsDefaultEnabled = obj.activeSelf };
                prop.TargetObjects.Add(new GUIDPathPair<GameObject>(ObjectPathStateType.RelativeFromObject, obj, root.gameObject));
                group.Props.Add(prop);
            }
            data.SaveToJson();
            status = "衣装を登録しました。元のEditorで適用して切替を生成してください。";
        }
    }
}
#endif

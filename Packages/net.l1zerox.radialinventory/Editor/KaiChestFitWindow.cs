        public static SkinnedMeshRenderer[] Collect(Avatar data,Group group,SkinnedMeshRenderer body,out string[] warnings)
        {
            var result=new HashSet<SkinnedMeshRenderer>();var notes=new List<string>();var root=data?.GetAvatarRoot()?.gameObject;
            if(root!=null&&group!=null)
                foreach(var prop in group.Props??new List<Prop>())
                {
                    if(prop==null)continue;
                    foreach(var reference in prop.TargetObjects??new List<GUIDPathPair<GameObject>>())
                    {
                        var target=reference?.GetObject(root);
                        if(target==null){notes.Add(prop.Name+"：参照不明の登録があります。");continue;}
                        if(target==root||!target.transform.IsChildOf(root.transform)){notes.Add(prop.Name+"：アバター全体・別アバターの登録を除外しました。");continue;}
                        var renderers=target.GetComponentsInChildren<SkinnedMeshRenderer>(true);
                        foreach(var r in renderers)if(r!=body&&r.sharedMesh!=null)result.Add(r);
                        if(renderers.Length==0)notes.Add(prop.Name+" / "+target.name+"：補正できるSkinned Meshがありません。");
                    }
                }
            warnings=notes.Distinct().ToArray();
            return result.OrderBy(r=>AnimationUtility.CalculateTransformPath(r.transform,root.transform)).ThenBy(r=>r.GetInstanceID()).ToArray();
        }
    }

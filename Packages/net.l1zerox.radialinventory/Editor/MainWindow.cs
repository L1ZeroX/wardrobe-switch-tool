    public partial class MainWindow : EditorWindow
    {
        private IndexedList indexedList = new IndexedList();
        private Vector2 scrollPosition = new Vector2();
        private bool showingVerticalScroll;
        private Rect tabScopeRect = new Rect();
        private Dictionary<RIS.MenuModeType, EditorTab> tabItems = null;
        private List<Avatar> avatars = null;
        private GUIStyle countBarStyleL;
        private GUIStyle countBarStyleR;
        private VRCAvatarDescriptor avatarRoot = null;
        private Avatar risAvatar = null;
        public static Avatar CurrentAvatar(GameObject root=null)
        {
            return Resources.FindObjectsOfTypeAll<MainWindow>().Select(w=>w.risAvatar)
                .FirstOrDefault(a=>a?.GetAvatarRoot()!=null&&(root==null||a.GetAvatarRoot().gameObject==root));
        }
        private bool isShowingJSONSelector = false;
        private void OnEnable() { titleContent = new GUIContent("衣装簡単切替ツール"); }
        [MenuItem("衣装簡単切替ツール/エディター", priority = 0)]
        private static void Create()
        {
            RISStrings.EditorInitialize();
            var window = GetWindow<MainWindow>("衣装簡単切替ツール");
            window.titleContent = new GUIContent("衣装簡単切替ツール");
            window.minSize = new Vector2(720, 740);
        }
        public static void OpenForAvatar(Avatar data)
        {
            Create();
            var window = GetWindow<MainWindow>();
            if (!ReferenceEquals(window.risAvatar, data)) { window.toolkitGroup = 0; window.toolkitProp = 0; window.toolkitSettings = false; window.propSearch = ""; }
            window.risAvatar = data;
            window.avatarRoot = data?.GetAvatarRoot();
            window.indexedList.index = Array.IndexOf(FindObjectsOfType<VRCAvatarDescriptor>(), window.avatarRoot);
            window.tabItems = new Dictionary<RIS.MenuModeType, EditorTab> {
                { RIS.MenuModeType.Simple, new TabSimple() }, { RIS.MenuModeType.Basic, new TabBasic() }, { RIS.MenuModeType.Advanced, new TabAdvanced() } };
            foreach (var tab in window.tabItems.Values) tab.InitializeTab(ref window.risAvatar);
            window.RefreshToolkit();
        }
        private void ShowJSONSelector()
        {
            var window = CreateInstance<SelectJSONWindow>();
            var avatarDescriptors = FindObjectsOfType(typeof(VRCAvatarDescriptor));
            avatarRoot = avatarDescriptors[indexedList.index] as VRCAvatarDescriptor;
            var loadedAvatar = avatars.Where(n => n.AvatarRoot == avatarRoot);

            foreach (var conflictedAvatar in loadedAvatar)
            {
                window.AddItem(conflictedAvatar.UniqueID, conflictedAvatar.LastWriteDate);
            }
            window.title = "RISV4 JSONSelector";
            window.ShowModal();
            Debug.LogWarning($"Multiple duplicate data were found. Use selected data. => {window.selectedUniqueID}");

            LoadAvatars();
            risAvatar = loadedAvatar.First(item => item.UniqueID == window.selectedUniqueID);
            foreach (var v in tabItems.Values)
                v.InitializeTab(ref risAvatar);
            isShowingJSONSelector = false;
        }
        private void LoadAvatars()
        {
            if(avatars == null)
                avatars = new List<Avatar>();
            else
                avatars.Clear();

            if (!Directory.Exists(RIS.AutoGeneratedFolderPath))
                Directory.CreateDirectory(RIS.AutoGeneratedFolderPath);
            var dirs = Directory.GetDirectories(RIS.AutoGeneratedFolderPath);
            foreach (var path in dirs)
            {
                var jsonPath = path.TrimEnd() + "\\" + RIS.SettingsFileName;
                if (File.Exists(jsonPath))
                {
                    try
                    {
                        var avatar = Avatar.LoadFromJson(jsonPath);
                        if (avatar != null && avatar.AvatarRoot != null && avatar.AvatarRoot.GetObject() != null)
                            avatars.Add(avatar);

                    }
                    catch(Exception ex)
                    {
                        Debug.LogError(ex);
                        EditorUtility.DisplayDialog(RISStrings.GetString("ris"), string.Format(RISStrings.GetString("broken_settings"), Path.GetDirectoryName(jsonPath)), RISStrings.GetString("ok"));
                    }
                }
            }
        }
        private void DrawLegacyEditor()
        {

            if(tabItems == null)
            {
                tabItems = new Dictionary<RIS.MenuModeType, EditorTab>();
                tabItems.Add(RIS.MenuModeType.Simple, new TabSimple());
                tabItems.Add(RIS.MenuModeType.Basic, new TabBasic());
                tabItems.Add(RIS.MenuModeType.Advanced, new TabAdvanced());
            }
            if (countBarStyleL == null)
                countBarStyleL = new GUIStyle(GUI.skin.label) { fontSize = 12, alignment = TextAnchor.UpperLeft, margin = new RectOffset(10, 10, 0, 0) };
            if (countBarStyleR == null)
                countBarStyleR = new GUIStyle(GUI.skin.label) { fontSize = 12, alignment = TextAnchor.UpperRight, margin = new RectOffset(10, 10, 0, 0) };
            if (avatars == null)
                LoadAvatars();
            using (var scrollScope = new EditorGUILayout.ScrollViewScope(scrollPosition))
            {
                using (var verticalScope = new EditorGUILayout.VerticalScope())
                {
                    scrollPosition = scrollScope.scrollPosition;
                    var showingVerticalScrollOld = showingVerticalScroll;
                    if (verticalScope.rect.height != 0)
                        showingVerticalScroll = verticalScope.rect.height >= position.size.y;
                    GUILayout.Label("① グループ → ② 衣装 → ③ 詳細・撮影 → 「適用する」で反映", KaiEditorUI.Hint);

                    if(RISV3toV4Updater.HasV3SettingsOnScene(RIS.SettingsNameV3))
                    {
                        EditorGUILayoutExtra.Separator();
                        EditorGUILayout.HelpBox(RISStrings.GetString("found_v3"), MessageType.Info);
                        if(GUILayout.Button(RISStrings.GetString("v3tov4")))
                        {
                            RISV3toV4Updater.SalvageDatas(RIS.SettingsNameV3);
                        }
                        EditorGUILayoutExtra.Separator();
                        EditorGUILayoutExtra.Space();
                    }
                    using (new EditorGUILayout.HorizontalScope())
                    {
                        GUILayout.Space(6);
                        GUILayout.Label("衣装簡単切替ツール " + RIS.CurrentVersion.Replace("ris_kai", ""), KaiEditorUI.Title, GUILayout.Height(KaiEditorUI.ControlHeight));
                        GUILayout.FlexibleSpace();
                        if (GUILayout.Button(new GUIContent("設定…", "表示する編集モードを選びます。"), KaiEditorUI.Button, GUILayout.Width(90))) KaiModeSettingsWindow.Open();
                        if (GUILayout.Button(new GUIContent("補助ツール…", "検索・衣装の一括登録・移行を開きます。"), KaiEditorUI.Button, GUILayout.Width(148))) KaiWardrobeWindow.Open(risAvatar);
                        if (GUILayout.Button("胸・衣装補正…", KaiEditorUI.Button, GUILayout.Width(136))) KaiChestFitWindow.OpenRegistered(risAvatar);
                        GUILayout.Space(6);
                    }
                    GUILayout.Space(4);
                    EditorGUI.BeginChangeCheck();
                    var avatarDescriptors = FindObjectsOfType(typeof(VRCAvatarDescriptor));
                    indexedList.list = avatarDescriptors.Select(n => n.name).ToArray();
                    using (new EditorGUILayout.HorizontalScope())
                    {
                        GUILayout.Space(6);
                        GUILayout.Label(RISStrings.GetString("target_avatar"), KaiEditorUI.Label, GUILayout.Width(KaiEditorUI.LabelWidth), GUILayout.Height(KaiEditorUI.ControlHeight));
                        indexedList.index = EditorGUILayoutExtra.IndexedStringList("", indexedList, RISStrings.GetString("unselected"), KaiEditorUI.Popup, GUILayout.Height(KaiEditorUI.ControlHeight));
                        GUILayout.Space(6);
                    }

                    if (!isShowingJSONSelector && (EditorGUI.EndChangeCheck() || (avatarRoot == null && indexedList.index != -1)))
                    {
                        LoadAvatars();
                        if (avatarDescriptors.Count() > 0 && indexedList.index >= 0 && indexedList.index < avatarDescriptors.Length)
                        {
                            avatarRoot = avatarDescriptors[indexedList.index] as VRCAvatarDescriptor;
                            var loadedAvatar = avatars.Where(n => n.AvatarRoot == avatarRoot);
                            if(loadedAvatar != null)
                            {
                                var count = loadedAvatar.Count();
                                if (count > 1)
                                {
                                    //重複データがある場合
                                    risAvatar = null;
                                    avatarRoot = null;
                                    isShowingJSONSelector = true;
                                    EditorApplication.delayCall += () => ShowJSONSelector();

                                }
                                else if(count == 1)
                                {
                                    risAvatar = loadedAvatar.First();
                                }
                                else
                                {
                                    risAvatar = KaiModeSettings.CreateAvatar();
                                }
                            }
                            if (avatarRoot != null)
                            {
                                foreach (var v in tabItems.Values)
                                    v.InitializeTab(ref risAvatar);
                            }
                        }
                        else
                        {
                            avatarRoot = null;
                            risAvatar = null;
                        }
                    }
                    var isRootNull = avatarRoot == null;
                    if (risAvatar == null)
                        risAvatar = KaiModeSettings.CreateAvatar();
                    if (!isRootNull && risAvatar != null && risAvatar.AvatarRoot?.GetObject() == null)
                    {
                        risAvatar.AvatarRoot.SetObject(avatarRoot);
                    }
                    using (new EditorGUI.DisabledGroupScope(isRootNull))
                    {
                        using (new EditorGUILayout.HorizontalScope())
                        {
                            if (GUILayout.Button(new GUIContent(RISStrings.GetString("export_file"), "現在の設定をJSONファイルとして保存します。"), KaiEditorUI.Button))
                            {
                                if (risAvatar.AvatarRoot.GetObject() == null)
                                    return;
                                var path = EditorUtility.SaveFilePanel(RISStrings.GetString("select_savepath"), "", $"RISSettings-{SafeParser.ParseFileName(risAvatar.AvatarRoot.GetObject().name)}.json", "json");
                                if (!string.IsNullOrEmpty(path))
                                {
                                    risAvatar.SaveToJson(path);
                                    EditorUtility.DisplayDialog(RISStrings.GetString("ris"), RISStrings.GetString("save_file"), RISStrings.GetString("ok"));
                                }
                            }
                            if (GUILayout.Button(new GUIContent(RISStrings.GetString("restore_file"), "保存済みの設定JSONを読み込みます。"), KaiEditorUI.Button))
                            {
                                var path = EditorUtility.OpenFilePanel(RISStrings.GetString("select_loadpath"), "", "json");
                                if (!string.IsNullOrEmpty(path))
                                {
                                    var avatar = Avatar.LoadFromJson(path);
                                    if (avatar == null) return;
                                    risAvatar.UseWriteDefaults = avatar.UseWriteDefaults;
                                    //risAvatar.OptimizeParameters = avatar.OptimizeParameters;
                                    //risAvatar.ApplyEnableDefault = avatar.ApplyEnableDefault;
                                    risAvatar.Groups = avatar.Groups;
                                    risAvatar.ExclusiveModes = avatar.ExclusiveModes;
                                    risAvatar.ExclusiveDisableClips = avatar.ExclusiveDisableClips;
                                    risAvatar.MenuMode = avatar.MenuMode;
                                    risAvatar.KaiAutoThumbnail = avatar.KaiAutoThumbnail;
                                    risAvatar.KaiUseDefaultGroup = avatar.KaiUseDefaultGroup;
                                    risAvatar.KaiExperimentalHeels = avatar.KaiExperimentalHeels;
                                    risAvatar.ForceReload();
                                    foreach (var v in tabItems.Values)
                                        v.InitializeTab(ref risAvatar);
                                    EditorUtility.DisplayDialog(RISStrings.GetString("ris"), RISStrings.GetString("load_file"), RISStrings.GetString("ok"));
                                }
                            }
                        }
                        GUILayout.Space(6);

                        KaiAutoThumbnail.DrawSettings(risAvatar);
                        var memoryAdded = 0;
                        using (new EditorGUILayout.VerticalScope())
                        {
                            using (new EditorGUILayout.HorizontalScope())
                            {
                                GUILayout.Space(5);
                                KaiModeSettings.DrawToolbar(risAvatar);
                                GUILayout.FlexibleSpace();
                                risAvatar.UseWriteDefaults = GUILayout.Toggle(risAvatar.UseWriteDefaults, new GUIContent(RISStrings.GetString("use_writedefaults"), "アニメーションのWrite Defaults設定。現在のアバターに合わせて設定してください。"), KaiEditorUI.Toggle, GUILayout.Width(340), GUILayout.Height(KaiEditorUI.ControlHeight));
                                GUILayout.Space(6);
                            }
                            KaiModeSettings.DrawRetainedModeNotice(risAvatar);
                            KaiDefaultOutfit.Draw(risAvatar);
                            KaiHeelLink.DrawGlobal(risAvatar);
                            var skin = new GUIStyle(GUI.skin.box);
                            skin.margin.top = 0;
                            using (var scope = new EditorGUILayout.VerticalScope(skin))
                            {
                                tabScopeRect = scope.rect;
                                if (tabItems.ContainsKey(risAvatar.MenuMode))
                                    tabItems[risAvatar.MenuMode].DrawTab(ref risAvatar, position, showingVerticalScroll && showingVerticalScrollOld);
                            }
                            KaiAutoThumbnail.Observe(risAvatar);
                            var memoryNow = 0;
                            var memoryUseFromScript = 0;
                            if (!isRootNull)
                            {
                                if (tabItems.ContainsKey(risAvatar.MenuMode))
                                {
                                    tabItems[risAvatar.MenuMode].CalculateMemoryCost(ref risAvatar, out memoryAdded, out memoryNow, out memoryUseFromScript);
                                }
                            }
                            EditorGUILayoutExtra.CostViewer(memoryNow, memoryAdded, memoryUseFromScript, RISStrings.GetString("using_memory"), RISStrings.GetString("remain_memory"), countBarStyleL, countBarStyleR);
                        }

                        string[] errors;
                        if (tabItems.ContainsKey(risAvatar.MenuMode))
                            errors = tabItems[risAvatar.MenuMode].CheckErrors(ref risAvatar);
                        else
                            errors = new string[] { };
                        var memoryOver = false;

                        UnityEditor.Animations.AnimatorController fxLayer = null;
                        if (!isRootNull) fxLayer = avatarRoot.GetFXLayer(RIS.AutoGeneratedFolderPath + risAvatar.UniqueID + "/", false);
                        EditorGUIUtility.labelWidth = 0;
                        var showFXWarning = fxLayer != null && !fxLayer.ValidateWriteDefaults(risAvatar.UseWriteDefaults);
                        var showParamInfo = !EditorSettings.OptimizeParameters;
                        memoryOver = KaiPreflight.Cost(risAvatar) > VRCExpressionParameters.MAX_PARAMETER_COST;
                        if (showFXWarning || showParamInfo || errors.Any() || memoryOver)
                            using (new EditorGUILayout.VerticalScope(GUI.skin.box))
                            {
                                if (memoryOver)
                                {
                                    EditorGUILayout.HelpBox(string.Format(RISStrings.GetString("err_overmemory"), VRCExpressionParameters.MAX_PARAMETER_COST), MessageType.Error);
                                }
                                foreach (var error in errors)
                                {
                                    EditorGUILayout.HelpBox(error, MessageType.Error);
                                }
                                if (showFXWarning)
                                {
                                    EditorGUILayout.HelpBox(RISStrings.GetString("warn_writedefaults"), MessageType.Warning);
                                }
                                if (showParamInfo)
                                {
                                    EditorGUILayout.HelpBox(RISStrings.GetString("warn_paramspace"), MessageType.Info);
                                }
                            }

                        EditorGUILayoutExtra.SeparatorWithSpace();
                        using (new EditorGUILayout.HorizontalScope())
                        {
                            using (new EditorGUI.DisabledGroupScope(errors.Any() || memoryOver))
                            {
                                if (GUILayout.Button(new GUIContent(RISStrings.GetString("attach"), "衣装設定・画像・Expressionsメニューをアバターへ反映します。"), KaiEditorUI.Button))
                                {
                                    risAvatar.SaveToJson();
                                    if (tabItems.ContainsKey(risAvatar.MenuMode))
                                        tabItems[risAvatar.MenuMode].ApplyToAvatar(ref risAvatar);
                                }
                            }
                            if (GUILayout.Button(new GUIContent(RISStrings.GetString("detach"), "このツールによるアバターへの適用を解除します。"), KaiEditorUI.Button))
                            {
                                tabItems[risAvatar.MenuMode].RemoveFromAvatar(ref risAvatar);
                            }
                        }
                    }
                    KaiEditorUI.DrawCredit();
                    GUILayout.FlexibleSpace();
                }
            }
        }
    }

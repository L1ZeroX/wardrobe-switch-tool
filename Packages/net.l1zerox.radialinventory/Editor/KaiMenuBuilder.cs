using System;
using System.Collections.Generic;
using System.Linq;
using UnityEditor;
using UnityEngine;
using VRC.SDK3.Avatars.ScriptableObjects;

namespace YagihataItems.RadialInventorySystemV4
{
    public static class KaiMenuBuilder
    {
        public const string DisplayName = "衣装簡単切替ツール";
        public static int PageCount(int count) { return count <= 8 ? 1 : 1 + PageCount(count - 7); }

        public static VRCExpressionsMenu Asset(string path)
        {
            UnityUtils.CreateFolderRecursively(System.IO.Path.GetDirectoryName(path).Replace('\\', '/'));
            var result = AssetDatabase.LoadAssetAtPath<VRCExpressionsMenu>(path);
            if (result == null)
            {
                result = ScriptableObject.CreateInstance<VRCExpressionsMenu>();
                AssetDatabase.CreateAsset(result, path);
            }
            return result;
        }

        public static void WritePages(VRCExpressionsMenu first, IList<VRCExpressionsMenu.Control> controls, string pagePrefix)
        {
            // Allocate all pages before changing references. Existing .meta GUIDs survive rebuilds.
            int count = PageCount(controls.Count);
            var pages = new List<VRCExpressionsMenu> { first };
            for (int i = 1; i < count; i++) pages.Add(Asset(pagePrefix + i + ".asset"));
            int offset = 0;
            for (int i = 0; i < count; i++)
            {
                int take = i == count - 1 ? 8 : 7;
                pages[i].controls = controls.Skip(offset).Take(take).ToList();
                offset += pages[i].controls.Count;
                if (i + 1 < count) pages[i].controls.Add(Link("次へ", pages[i + 1], TexAssets.GroupIcon));
                EditorUtility.SetDirty(pages[i]);
            }
        }

        static VRCExpressionsMenu.Control Link(string name, VRCExpressionsMenu menu, Texture2D icon)
        {
            return new VRCExpressionsMenu.Control { name = name, subMenu = menu, icon = icon,
                type = VRCExpressionsMenu.Control.ControlType.SubMenu };
        }

        // Clone the graph, including shared/cyclic submenus, instead of modifying third-party menus.
        static List<VRCExpressionsMenu.Control> CopyControls(VRCExpressionsMenu source, string folder,
            Dictionary<VRCExpressionsMenu, VRCExpressionsMenu> copies, bool root = false)
        {
            var result = new List<VRCExpressionsMenu.Control>();
            if (source == null) return result;
            foreach (var control in source.controls ?? new List<VRCExpressionsMenu.Control>())
            {
                if (control == null) continue;
                if (root && (control.name == "Radial Inventory" || control.name == "Radial Inventory改" || control.name == DisplayName) && control.subMenu != null &&
                    AssetDatabase.GetAssetPath(control.subMenu).StartsWith(RIS.AutoGeneratedFolderPath, StringComparison.Ordinal)) continue;
                // Unity serialization also copies puppet labels/parameters without sharing mutable arrays.
                var clone = JsonUtility.FromJson<VRCExpressionsMenu.Control>(JsonUtility.ToJson(control));
                if (control.subMenu != null)
                {
                    VRCExpressionsMenu sub;
                    if (!copies.TryGetValue(control.subMenu, out sub))
                    {
                        string guid = AssetDatabase.AssetPathToGUID(AssetDatabase.GetAssetPath(control.subMenu));
                        if (string.IsNullOrEmpty(guid)) throw new InvalidOperationException("保存されていないメニューがあります。");
                        sub = Asset(folder + guid + ".asset");
                        copies.Add(control.subMenu, sub);
                        WritePages(sub, CopyControls(control.subMenu, folder, copies), folder + guid + "_page");
                    }
                    clone.subMenu = sub;
                }
                result.Add(clone);
            }
            return result;
        }

        public static void Build(Avatar data, string folder)
        {
            var avatar = data.GetAvatarRoot();
            if (avatar == null) return;
            KaiGroupThumbnail.CompletePending(data);
            UnityUtils.CreateFolderRecursively(folder);
            var state = AssetDatabase.LoadAssetAtPath<KaiMenuState>(folder + "KaiMenuState.asset");
            if (state == null)
            {
                state = ScriptableObject.CreateInstance<KaiMenuState>();
                AssetDatabase.CreateAsset(state, folder + "KaiMenuState.asset");
            }
            if (avatar.expressionsMenu != state.outputRoot) state.sourceRoot = avatar.expressionsMenu;
            var main = Asset(folder + "RadInvMainMenu.asset");
            var groupControls = new List<VRCExpressionsMenu.Control>();
            var copies = new Dictionary<VRCExpressionsMenu, VRCExpressionsMenu>();
            for (int g = 0; g < data.Groups.Count; g++)
            {
                var group = data.Groups[g];
                if (data.MenuMode == RIS.MenuModeType.Simple && (group.Props.Count == 0 || (g == 7 && !group.Props.Any(p => p.PropSets.Any(s => s != null))))) continue;
                var menu = Asset(folder + "SubMenus/Group" + g + "Menu.asset");
                var controls = CopyControls(data.MenuMode == RIS.MenuModeType.Advanced ? group.BaseMenu?.GetObject() : null, folder + "ExternalMenus/", copies);
                bool setGroup = data.MenuMode == RIS.MenuModeType.Simple && g == 7;
                bool wholeGroup = KaiGroupSwitch.Enabled(data, g);
                if (wholeGroup)
                {
                    controls.Add(KaiGroupSwitch.Control(data, g, true));
                    controls.Add(KaiGroupSwitch.Control(data, g, false));
                    controls.Add(KaiGroupSwitch.Setting("他の衣装を自動OFF", KaiGroupSwitch.AutoOff(g)));
                }
                if (data.MenuMode != RIS.MenuModeType.Simple)
                    controls.Add(KaiGroupSwitch.Setting("このグループを保持", KaiGroupSwitch.Keep(g)));
                if (group.UseResetButton && data.MenuMode != RIS.MenuModeType.Simple)
                    controls.Add(new VRCExpressionsMenu.Control { name = "リセット", icon = TexAssets.ReloadIcon,
                        type = VRCExpressionsMenu.Control.ControlType.Toggle, value = 1,
                        parameter = new VRCExpressionsMenu.Control.Parameter { name = RIS.Prefix + "-G" + g + "RESET" } });
                var propControls = new List<VRCExpressionsMenu.Control>();
                for (int p = 0; p < group.Props.Count; p++)
                {
                    var prop = group.Props[p];
                    var name = prop.GetPropName(data);
                    propControls.Add(new VRCExpressionsMenu.Control { name = string.IsNullOrEmpty(name) ? string.Format(RISStrings.GetString(setGroup ? "defaultname_set" : "defaultname_prop"), p) : name,
                        icon = prop.Icon?.GetObject() ?? TexAssets.BoxIcon,
                        type = VRCExpressionsMenu.Control.ControlType.Toggle, value = setGroup ? p + 1 : 1,
                        parameter = new VRCExpressionsMenu.Control.Parameter { name = setGroup ? RIS.Prefix + "-SET" : RIS.Prefix + "-G" + g + "P" + p } });
                }
                if (wholeGroup)
                {
                    var individual = Asset(folder + "SubMenus/Group" + g + "Individual.asset");
                    WritePages(individual, propControls, folder + "SubMenus/Group" + g + "Individual_page");
                    controls.Insert(0, Link("個別に切り替え", individual, group.Icon?.GetObject() ?? TexAssets.GroupIcon));
                }
                else controls.AddRange(propControls);
                WritePages(menu, controls, folder + "SubMenus/Group" + g + "_page");
                var groupName = group.Name;
                if (data.MenuMode == RIS.MenuModeType.Simple)
                {
                    var names = new[] { "item_head", "item_hand", "item_foot", "item_chest", "item_hip", "item_accessory1", "item_accessory2", "costume_set" };
                    groupName = RISStrings.GetString(names[g]);
                }
                groupControls.Add(Link(string.IsNullOrEmpty(groupName) ? string.Format(RISStrings.GetString("defaultname_group"), g) : groupName,
                    menu, group.Icon?.GetObject() ?? TexAssets.GroupIcon));
            }
            WritePages(main, groupControls, folder + "Main_page");
            state.outputRoot = Asset(folder + "KaiRootMenu.asset");
            var rootControls = CopyControls(state.sourceRoot, folder + "ExternalMenus/", copies, true);
            rootControls.Add(Link(DisplayName, main, TexAssets.MenuIcon));
            WritePages(state.outputRoot, rootControls, folder + "Root_page");
            avatar.customExpressions = true;
            avatar.expressionsMenu = state.outputRoot;
            state.detached = false;
            EditorUtility.SetDirty(state);
            EditorUtility.SetDirty(avatar);
            AssetDatabase.SaveAssets();
        }
        public static void Detach(Avatar data, string folder)
        {
            var state = AssetDatabase.LoadAssetAtPath<KaiMenuState>(folder + "KaiMenuState.asset");
            var avatar = data.GetAvatarRoot();
            if (state == null || avatar == null || avatar.expressionsMenu != state.outputRoot) return;
            var controls = CopyControls(state.sourceRoot, folder + "ExternalMenus/", new Dictionary<VRCExpressionsMenu, VRCExpressionsMenu>(), true);
            WritePages(state.outputRoot, controls, folder + "Root_page");
            state.detached = true;
            EditorUtility.SetDirty(state);
        }
    }
}

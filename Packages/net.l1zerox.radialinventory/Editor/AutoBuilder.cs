using System;
using System.IO;
using System.Linq;
using UnityEngine;
using VRC.SDKBase.Editor.BuildPipeline;

namespace YagihataItems.RadialInventorySystemV4
{
    public class AutoBuilder : IVRCSDKBuildRequestedCallback
    {
        public int callbackOrder => 10;
        public bool OnBuildRequested(VRCSDKRequestedBuildType type)
        {
            if (type != VRCSDKRequestedBuildType.Avatar || (!EditorSettings.AutoSetupMenu && !EditorSettings.AutoSetupParams)) return true;
            try
            {
                if (!Directory.Exists(RIS.AutoGeneratedFolderPath)) return true;
                var data = Directory.GetFiles(RIS.AutoGeneratedFolderPath, RIS.SettingsFileName, SearchOption.AllDirectories)
                    .Select(Avatar.LoadFromJson).Where(a => a != null && a.GetAvatarRoot() != null && a.GetAvatarRoot().gameObject.activeInHierarchy)
                    .GroupBy(a => a.GetAvatarRoot()).Select(g => g.OrderByDescending(a => a.LastWriteDate).First()).ToList();
                // Validate every avatar before touching any generated assets.
                foreach (var avatar in data) { var state = UnityEditor.AssetDatabase.LoadAssetAtPath<KaiMenuState>(RIS.AutoGeneratedFolderPath + avatar.UniqueID + "/KaiMenuState.asset"); if (state == null || !state.detached) KaiPreflight.Require(avatar); }
                foreach (var avatar in data) CheckExpressionMenu(avatar);
                return true;
            }
            catch (Exception e) { Debug.LogError("衣装簡単切替ツール: " + e.Message); return false; }
        }
        public void CheckExpressionMenu(Avatar avatar)
        {
            var state = UnityEditor.AssetDatabase.LoadAssetAtPath<KaiMenuState>(RIS.AutoGeneratedFolderPath + avatar.UniqueID + "/KaiMenuState.asset");
            if (state != null && state.detached) return;
            KaiPreflight.Require(avatar);
            if (EditorSettings.AutoSetupMenu) avatar.ReCreateExpressionMenu();
            if (EditorSettings.AutoSetupParams && avatar.GetAvatarRoot().expressionParameters == null) avatar.ReCreateExpressionParams();
        }
    }
}
#endif
